const ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";

export function randomId(prefix: string, len = 14): string {
  const bytes = new Uint8Array(len);
  crypto.getRandomValues(bytes);
  let s = prefix;
  for (const b of bytes) s += ALPHABET[b % 62];
  return s;
}

export const newFieldId = () => randomId("fld");
export const newTableId = () => randomId("tbl");
export const newViewId = () => randomId("viw");
export const newChoiceId = () => randomId("sel", 10);
export const newAttachmentId = () => randomId("att");
export const newDashboardId = () => randomId("dsh");
export const newWidgetId = () => randomId("wgt", 10);
export const newAutomationId = () => randomId("aut");
export const newAiServiceId = () => randomId("ais");
export const newWebhookToken = () => randomId("", 32);

/** Ids generated by randomId are safe to embed in SQL JSON paths; everything else is rejected. */
export function isSafeId(id: unknown): id is string {
  return typeof id === "string" && /^[A-Za-z0-9_]{3,40}$/.test(id);
}
